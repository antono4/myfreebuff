def sample_payload(fields: list[dict[str, Any]]) -> dict[str, Any]:
    """A valid create body for the generated smoke test."""
    return {f["name"]: _SAMPLE_VALUES.get(f.get("type", "string"), "smoke") for f in fields}


def json_literal(value: Any) -> str:
    return json.dumps(value)
