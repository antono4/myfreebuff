from typing import Any


def render(template: str, **values: Any) -> str:
    """Replace every ``{{KEY}}`` occurrence with ``values[KEY]``."""
    out = template
    for key, value in values.items():
        out = out.replace("{{" + key + "}}", str(value))
    return out


