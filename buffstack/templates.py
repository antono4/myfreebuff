"""Templates for the projects BuffStack generates.

These are real, runnable files rather than stubs: a Flask app with a working
in-memory JSON API and an HTML dashboard that fetches from it. The agent
scaffolds from these, then edits them with the other tools.

Placeholders use ``{{TOKEN}}`` and are applied with :func:`render`. That avoids
``string.Template`` and ``str.format``, whose metacharacters (``$``, ``{}``)
collide with the JavaScript and CSS in these files.
"""

